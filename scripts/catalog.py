#!/usr/bin/env python3
"""Build the repository catalog from project READMEs (standard library only)."""
from __future__ import annotations

import argparse
import re
from collections import Counter
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
EXCLUDED = {'.git', '.github', 'docs', 'scripts'}


def projects():
    for folder in sorted(ROOT.iterdir(), key=lambda p: p.name.casefold()):
        if folder.is_dir() and folder.name not in EXCLUDED:
            yield folder


def describe(folder):
    readme = folder / 'README.md'
    text = readme.read_text(encoding='utf-8') if readme.exists() else ''
    title = next((line.lstrip('# ').strip() for line in text.splitlines() if line.startswith('# ')), folder.name)
    if (folder / 'main.py').exists() and (folder / 'prompt.py').exists():
        kind = 'Python templates'
    elif any('"nodes"' in p.read_text(encoding='utf-8', errors='replace') and '"connections"' in p.read_text(encoding='utf-8', errors='replace') for p in folder.glob('*.json')) or (folder / 'JSON').exists():
        kind = 'n8n workflows'
    elif any(p.is_dir() for p in folder.iterdir()) and not any((folder / name).exists() for name in ('main.py', 'app.py', 'package.json', 'pyproject.toml', 'manifest.json')) and re.match(r'^\d+-(ai|biz)', folder.name):
        kind = 'Collections'
    else:
        kind = 'Applications and other projects'
    industry = re.search(r'Industry (?:template|focus):\s*\*\*(.+?)\*\*', text)
    detail = industry.group(1) if industry else ''
    return title.replace('|', '\\|'), kind, detail.replace('|', '\\|')


def render():
    entries = [(p, *describe(p)) for p in projects()]
    counts = Counter(entry[2] for entry in entries)
    lines = ['# Project catalog', '', 'Generated by `python3 scripts/catalog.py`. Search this page by name or industry.', '',
             f'{len(entries)} top-level project folders. Collections may contain additional nested projects.', '']
    for kind in ('Python templates', 'n8n workflows', 'Collections', 'Applications and other projects'):
        lines.extend([f'## {kind} ({counts[kind]})', '', '| Project | Folder | Industry |', '| --- | --- | --- |'])
        for folder, title, category, detail in entries:
            if category == kind:
                path = quote(folder.name, safe='')
                lines.append(f'| [{title}](../{path}/) | `{folder.name}` | {detail} |')
        lines.append('')
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the committed catalog is stale')
    args = parser.parse_args()
    target = ROOT / 'docs' / 'CATALOG.md'
    content = render()
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != content:
            raise SystemExit('Catalog is stale. Run: python3 scripts/catalog.py')
    else:
        target.write_text(content, encoding='utf-8')


if __name__ == '__main__':
    main()
